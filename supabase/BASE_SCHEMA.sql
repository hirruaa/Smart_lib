  create or replace function public.admin_review_book_contribution(
    contribution_id bigint,
    decision text,
    reward_points integer default 25,
    access_points integer default 0
  )
  returns public.book_contributions language plpgsql security definer set search_path = public as $$
  declare
    contribution public.book_contributions;
    created_book_id bigint;
  begin
    if not public.is_admin() then raise exception 'Administrator access required'; end if;
    if decision not in ('approved', 'rejected') then raise exception 'Invalid contribution decision'; end if;
    if reward_points < 0 or reward_points > 100 then raise exception 'Reward must be between 0 and 100 points'; end if;
    if access_points < 0 then raise exception 'Access cost cannot be negative'; end if;

    select * into contribution from public.book_contributions where id = contribution_id for update;
    if contribution.id is null or contribution.status <> 'pending' then raise exception 'Pending contribution not found'; end if;

    if decision = 'approved' then
      insert into public.books(title, author, category, description, pdf_url, access_points)
      values (contribution.title, contribution.author, 'Community contribution', contribution.description, contribution.pdf_url, access_points)
      returning id into created_book_id;
      update public.profiles set points_balance = points_balance + reward_points where id = contribution.user_id;
      if reward_points > 0 then
        insert into public.point_transactions(user_id, amount, transaction_type, reference_id, description)
        values (contribution.user_id, reward_points, 'contribution_reward', contribution.id, 'Approved library contribution');
      end if;
    end if;

    update public.book_contributions
    set status = decision,
        points_awarded = case when decision = 'approved' then reward_points else 0 end,
        approved_book_id = created_book_id,
        reviewed_by = auth.uid(),
        reviewed_at = now()
    where id = contribution.id
    returning * into contribution;
    insert into public.notifications(user_id, event_type, title, message, reference_id)
    values (
      contribution.user_id,
      'contribution_review',
      case when decision = 'approved' then 'Contribution approved' else 'Contribution reviewed' end,
      case when decision = 'approved' then 'Your resource was added to the library.' else 'Your submitted resource was not approved.' end,
      contribution.id
    );
    return contribution;
  end;
  $$;

  create or replace function public.admin_set_profile_role(target_user_id uuid, new_role text)
  returns public.profiles language plpgsql security definer set search_path = public as $$
  declare
    updated_profile public.profiles;
  begin
    if not public.is_admin() then raise exception 'Administrator access required'; end if;
    if new_role not in ('student', 'admin') then raise exception 'Invalid account role'; end if;
    update public.profiles set role = new_role where id = target_user_id returning * into updated_profile;
    if updated_profile.id is null then raise exception 'Profile not found'; end if;
    return updated_profile;
  end;
  $$;

  create or replace function public.admin_decide_borrow_request(request_id bigint, decision text)
  returns public.borrow_requests language plpgsql security definer set search_path = public as $$
  declare
    updated_request public.borrow_requests;
  begin
    if not public.is_admin() then raise exception 'Administrator access required'; end if;
    if decision not in ('approved', 'rejected') then raise exception 'Invalid request decision'; end if;
    update public.borrow_requests
    set status = decision,
        due_date = case when decision = 'approved' then now() + make_interval(days => duration_days) else null end
    where id = request_id and status = 'pending'
    returning * into updated_request;
    if updated_request.id is null then raise exception 'Pending request not found'; end if;
    return updated_request;
  end;
  $$;

  create or replace function public.renew_digital_loan(request_id bigint, extension_days integer default 14)
  returns public.borrow_requests language plpgsql security definer set search_path = public as $$
  declare
    updated_request public.borrow_requests;
  begin
    if auth.uid() is null then raise exception 'Authentication required'; end if;
    if extension_days < 7 or extension_days > 30 then raise exception 'Renewal must be between 7 and 30 days'; end if;
    update public.borrow_requests
    set due_date = greatest(coalesce(due_date, now()), now()) + make_interval(days => extension_days),
        renewal_count = renewal_count + 1
    where id = request_id and student_id = auth.uid() and status = 'approved'
      and returned_date is null and due_date > now() and renewal_count < 2
    returning * into updated_request;
    if updated_request.id is null then raise exception 'Loan cannot be renewed'; end if;
    return updated_request;
  end;
  $$;

  create or replace function public.return_digital_loan(request_id bigint)
  returns public.borrow_requests language plpgsql security definer set search_path = public as $$
  declare
    updated_request public.borrow_requests;
  begin
    if auth.uid() is null then raise exception 'Authentication required'; end if;
    update public.borrow_requests
    set status = 'returned', returned_date = now()
    where id = request_id and student_id = auth.uid() and status = 'approved' and returned_date is null
    returning * into updated_request;
    if updated_request.id is null then raise exception 'Loan cannot be returned'; end if;
    return updated_request;
  end;
  $$;

  create or replace function public.revoke_digital_loan(request_id bigint)
  returns public.borrow_requests language plpgsql security definer set search_path = public as $$
  declare
    updated_request public.borrow_requests;
  begin
    if not public.is_admin() then raise exception 'Administrator access required'; end if;
    update public.borrow_requests
    set status = 'revoked', returned_date = now()
    where id = request_id and status = 'approved' and returned_date is null
    returning * into updated_request;
    if updated_request.id is null then raise exception 'Approved loan not found or already closed'; end if;
    return updated_request;
  end;
  $$;

