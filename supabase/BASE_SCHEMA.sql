  create or replace function public.enqueue_borrow_request_notifications()
  returns trigger language plpgsql security definer set search_path = public as $$
  begin
    if old.status is distinct from new.status and new.status in ('approved', 'rejected') then
      insert into public.email_queue(event_type, payload)
      values ('borrow_request_status', jsonb_build_object(
        'student_id', new.student_id,
        'book_id', new.book_id,
        'status', new.status,
        'request_id', new.id
      ));
      insert into public.notifications(user_id, event_type, title, message, reference_id)
      values (
        new.student_id,
        'borrow_request_status',
        case when new.status = 'approved' then 'Access approved' else 'Request update' end,
        case when new.status = 'approved' then 'Your digital library request was approved.' else 'Your digital library request was not approved.' end,
        new.id
      );
    end if;
    return new;
  end;
  $$;

