create or replace function public.enqueue_borrow_request_notifications()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if old.status is distinct from new.status and new.status in ('approved', 'rejected') then
    insert into public.email_queue(event_type, payload)
    values ('borrow_request_status', jsonb_build_object(
      'student_id', new.student_id,
      'book_id', new.book_id,
      'status', new.status,
      'request_id', new.id
    ));
  end if;
  return new;
end;
$$;

drop trigger if exists trg_enqueue_borrow_request_notifications on public.borrow_requests;
create trigger trg_enqueue_borrow_request_notifications
after update on public.borrow_requests
for each row execute function public.enqueue_borrow_request_notifications();

create or replace function public.calculate_overdue_fines(daily_rate numeric default 0.5)
returns void language plpgsql security definer set search_path = public as $$
declare
  loan record;
  days_overdue integer;
begin
  for loan in
    select id, student_id, due_date
    from public.borrow_requests
    where status = 'approved' and due_date is not null
      and (returned_date is null or returned_date > due_date)
  loop
    days_overdue := greatest(0, date_part('day', now()::date - loan.due_date::date)::integer);
    if days_overdue > 0 then
      insert into public.fines(borrow_request_id, student_id, amount)
      values (loan.id, loan.student_id, days_overdue * daily_rate)
      on conflict (borrow_request_id) do update
      set amount = excluded.amount, status = 'unpaid', created_at = now();
    end if;
  end loop;
end;
$$;

create or replace function public.request_digital_loan(p_book_id bigint, p_duration_days integer)
returns public.borrow_requests language plpgsql security definer set search_path = public as $$
declare
  requested public.borrow_requests;
  active_count integer;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  if p_duration_days < 7 or p_duration_days > 90 then
    raise exception 'Choose a lending period between 7 and 90 days';
  end if;

  perform pg_advisory_xact_lock(hashtextextended(auth.uid()::text || ':' || p_book_id::text, 0));
  if not exists (select 1 from public.books where id = p_book_id) then
    raise exception 'Resource not found';
  end if;

  select count(*) into active_count
  from public.borrow_requests
  where student_id = auth.uid() and status = 'approved'
    and returned_date is null and due_date > now();
  if active_count >= 3 then
    raise exception 'You have reached the maximum of 3 active digital loans';
  end if;

  if exists (
    select 1 from public.borrow_requests
    where student_id = auth.uid() and book_id = p_book_id
      and (status = 'pending' or (status = 'approved' and returned_date is null and due_date > now()))
  ) then
    raise exception 'You already have an active request or loan for this resource';
  end if;

  insert into public.borrow_requests(student_id, book_id, duration_days)
  values (auth.uid(), p_book_id, p_duration_days)
  returning * into requested;
  return requested;
end;
$$;

create or replace function public.provision_profile()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, role)
  values (new.id, coalesce(new.email, ''), 'student')
  on conflict (id) do update set email = excluded.email;
  return new;
end;
$$;

