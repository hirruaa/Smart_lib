create or replace function public.prevent_student_role_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if old.role is distinct from new.role
     and auth.uid() is not null
     and not exists (select 1 from public.profiles where id = auth.uid() and role = 'admin') then
    raise exception 'Only an administrator can change account roles';
  end if;
  return new;
end;
$$;

drop trigger if exists trg_profiles_role_guard on public.profiles;
create trigger trg_profiles_role_guard
before update on public.profiles
for each row execute function public.prevent_student_role_change();

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin');
$$;

create or replace function public.admin_set_profile_role(target_user_id uuid, new_role text)
returns public.profiles language plpgsql security definer set search_path = public as $$
declare
  updated_profile public.profiles;
begin
  if not public.is_admin() then raise exception 'Administrator access required'; end if;
  if new_role not in ('student', 'admin') then raise exception 'Invalid account role'; end if;
  update public.profiles set role = new_role where id = target_user_id returning * into updated_profile;
  if updated_profile.id is null then raise exception 'Profile not found'; end if;
  return updated_profile;
end;
$$;

create or replace function public.admin_decide_borrow_request(request_id bigint, decision text)
returns public.borrow_requests language plpgsql security definer set search_path = public as $$
declare
  updated_request public.borrow_requests;
begin
  if not public.is_admin() then raise exception 'Administrator access required'; end if;
  if decision not in ('approved', 'rejected') then raise exception 'Invalid request decision'; end if;
  update public.borrow_requests
  set status = decision,
      due_date = case when decision = 'approved' then now() + make_interval(days => duration_days) else null end
  where id = request_id and status = 'pending'
  returning * into updated_request;
  if updated_request.id is null then raise exception 'Pending request not found'; end if;
  return updated_request;
end;
$$;

create or replace function public.renew_digital_loan(request_id bigint, extension_days integer default 14)
returns public.borrow_requests language plpgsql security definer set search_path = public as $$
declare
  updated_request public.borrow_requests;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  if extension_days < 7 or extension_days > 30 then raise exception 'Renewal must be between 7 and 30 days'; end if;
  update public.borrow_requests
  set due_date = greatest(coalesce(due_date, now()), now()) + make_interval(days => extension_days),
      renewal_count = renewal_count + 1
  where id = request_id and student_id = auth.uid() and status = 'approved'
    and returned_date is null and due_date > now() and renewal_count < 2
  returning * into updated_request;
  if updated_request.id is null then raise exception 'Loan cannot be renewed'; end if;
  return updated_request;
end;
$$;

create or replace function public.return_digital_loan(request_id bigint)
returns public.borrow_requests language plpgsql security definer set search_path = public as $$
declare
  updated_request public.borrow_requests;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  update public.borrow_requests
  set status = 'returned', returned_date = now()
  where id = request_id and student_id = auth.uid() and status = 'approved' and returned_date is null
  returning * into updated_request;
  if updated_request.id is null then raise exception 'Loan cannot be returned'; end if;
  return updated_request;
end;
$$;

