  create table if not exists public.profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    email text not null,
    full_name text,
    role text not null default 'student' check (role in ('student', 'admin')),
    created_at timestamptz not null default now()
  );

  grant select, insert, update on public.profiles to authenticated;

  alter table public.profiles add column if not exists points_balance integer not null default 0;
  alter table public.profiles drop constraint if exists profiles_points_balance_check;
  alter table public.profiles add constraint profiles_points_balance_check check (points_balance >= 0);

  create table if not exists public.books (
    id bigint generated by default as identity primary key,
    title text not null,
    author text not null,
    category text not null,
    isbn text,
    description text,
    pdf_url text,
    -- Legacy compatibility fields. Digital loan eligibility must not use these values.
    total_copies integer not null default 1 check (total_copies >= 0),
    available_copies integer not null default 1 check (available_copies >= 0),
    search_vector tsvector,
    access_points integer not null default 0,
    page_count integer check (page_count is null or page_count > 0),
    created_at timestamptz not null default now(),
    check (available_copies <= total_copies)
  );

  alter table public.books add column if not exists access_points integer not null default 0;
  alter table public.books add column if not exists page_count integer;
  alter table public.books drop constraint if exists books_page_count_check;
  alter table public.books add constraint books_page_count_check check (page_count is null or page_count > 0);
  alter table public.books drop constraint if exists books_access_points_check;
  alter table public.books add constraint books_access_points_check check (access_points >= 0);

