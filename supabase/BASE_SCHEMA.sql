create or replace function public.sync_book_search_vector()
returns trigger
language plpgsql
as $$
begin
  new.search_vector := to_tsvector(
    'english',
    coalesce(new.title, '') || ' ' ||
    coalesce(new.author, '') || ' ' ||
    coalesce(new.description, '') || ' ' ||
    coalesce(new.category, '')
  );
  return new;
end;
$$;

drop trigger if exists trg_books_search_vector on public.books;
create trigger trg_books_search_vector
before insert or update on public.books
for each row execute function public.sync_book_search_vector();

update public.books
set search_vector = to_tsvector(
  'english',
  coalesce(title, '') || ' ' || coalesce(author, '') || ' ' ||
  coalesce(description, '') || ' ' || coalesce(category, '')
)
where search_vector is null;

create or replace function public.search_books(p_query text, p_limit integer default 10)
returns table(
  id bigint,
  title text,
  author text,
  category text,
  description text,
  pdf_url text,
  available_copies integer,
  rank double precision
)
language sql
stable
security invoker
as $$
  select b.id, b.title, b.author, b.category, b.description, b.pdf_url,
         b.available_copies,
         ts_rank(b.search_vector, plainto_tsquery('english', p_query)) as rank
  from public.books b
  where b.search_vector @@ plainto_tsquery('english', p_query)
  order by rank desc
  limit least(greatest(coalesce(p_limit, 10), 1), 50);
$$;

