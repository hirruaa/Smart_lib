create extension if not exists pg_trgm;
create extension if not exists "uuid-ossp";

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  full_name text,
  role text not null default 'student' check (role in ('student', 'admin')),
  created_at timestamptz not null default now()
);

grant select, insert, update on public.profiles to authenticated;

create table if not exists public.books (
  id bigint generated by default as identity primary key,
  title text not null,
  author text not null,
  category text not null,
  isbn text,
  description text,
  pdf_url text,
  -- Legacy compatibility fields. Digital loan eligibility must not use these values.
  total_copies integer not null default 1 check (total_copies >= 0),
  available_copies integer not null default 1 check (available_copies >= 0),
  search_vector tsvector,
  created_at timestamptz not null default now(),
  check (available_copies <= total_copies)
);

create table if not exists public.borrow_requests (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.profiles(id) on delete cascade,
  book_id bigint not null references public.books(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected', 'returned')),
  request_date timestamptz not null default now(),
  due_date timestamptz,
  returned_date timestamptz,
  duration_days integer not null default 14 check (duration_days between 7 and 90),
  renewal_count integer not null default 0 check (renewal_count >= 0),
  notes text,
  created_at timestamptz not null default now()
);

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  book_id bigint not null references public.books(id) on delete cascade,
  student_id uuid not null references public.profiles(id) on delete cascade,
  rating integer not null check (rating between 1 and 5),
  comment text,
  created_at timestamptz not null default now(),
  unique (book_id, student_id)
);

create table if not exists public.wishlists (
  id bigint generated by default as identity primary key,
  book_id bigint not null references public.books(id) on delete cascade,
  student_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (book_id, student_id)
);

create table if not exists public.study_notes (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  book_id bigint not null references public.books(id) on delete cascade,
  page integer,
  text text,
  selection_text text,
  meta jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.highlights (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  book_id bigint not null references public.books(id) on delete cascade,
  page integer not null,
  rects jsonb not null,
  color text not null default 'yellow',
  note_id bigint references public.study_notes(id) on delete set null,
  meta jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.fines (
  id bigint generated by default as identity primary key,
  borrow_request_id bigint not null unique references public.borrow_requests(id) on delete cascade,
  student_id uuid not null references public.profiles(id) on delete cascade,
  amount numeric(10, 2) not null default 0 check (amount >= 0),
  status text not null default 'unpaid' check (status in ('unpaid', 'paid')),
  created_at timestamptz not null default now(),
  paid_at timestamptz
);

create table if not exists public.email_queue (
  id bigint generated by default as identity primary key,
  event_type text not null,
  payload jsonb not null,
  processed boolean not null default false,
  created_at timestamptz not null default now(),
  processed_at timestamptz
);

create table if not exists public.assistant_sessions (
  id uuid primary key default uuid_generate_v4(),
  user_id uuid not null references public.profiles(id) on delete cascade,
  title text not null default 'New research chat',
