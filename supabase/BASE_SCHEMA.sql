  grant execute on function public.admin_create_reward(text, text, integer, text, integer) to authenticated;
  grant execute on function public.admin_set_reward_active(bigint, boolean) to authenticated;

  -- Ensure storage policy allows the protected ebook workflow used by the app.
  drop policy if exists "Students upload contribution PDFs" on storage.objects;
  create policy "Students upload contribution PDFs" on storage.objects
  for insert to authenticated
  with check (
    bucket_id = 'ebooks'
    and name like 'contributions/' || auth.uid()::text || '/%'
  );

  drop policy if exists "Owners and admins read contribution PDFs" on storage.objects;
  create policy "Owners and admins read contribution PDFs" on storage.objects
  for select to authenticated
  using (
    bucket_id = 'ebooks'
    and (
      public.is_admin()
      or name like 'contributions/' || auth.uid()::text || '/%'
      or exists (
        select 1 from public.books b
        join public.borrow_requests br on br.book_id = b.id
        where (b.storage_path = name or b.pdf_url = name or b.pdf_url like '%' || name)
          and br.student_id = auth.uid()
          and br.status = 'approved'
          and br.returned_date is null
          and br.due_date > now()
      )
      or exists (
        select 1 from public.books b
        join public.book_access_grants bag on bag.book_id = b.id
        where (b.storage_path = name or b.pdf_url = name or b.pdf_url like '%' || name)
          and bag.student_id = auth.uid()
          and bag.status = 'active'
          and bag.expires_at > now()
      )
    )
  );

  -- This block intentionally avoids using direct table-level inserts for student uploads.
  revoke insert on public.book_contributions from anon, authenticated;

  -- Add optional service table indexes to keep admin analytics responsive.
  create index if not exists idx_book_access_grants_student_status on public.book_access_grants(student_id, status, expires_at);
  create index if not exists idx_book_access_grants_book_status on public.book_access_grants(book_id, status);
  create index if not exists idx_rewards_active on public.rewards(is_active, reward_type);
  create index if not exists idx_audit_logs_created on public.audit_logs(created_at desc);
  create index if not exists idx_recognition_awards_student on public.recognition_awards(student_id, created_at desc);

