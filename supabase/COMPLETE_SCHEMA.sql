  perform pg_advisory_xact_lock(hashtextextended('physical-book:' || target_request.book_id::text, 0));
  update public.physical_book_requests
  set status = p_decision, reservation_expires_at = null
  where id = p_request_id returning * into target_request;
  update public.physical_book_copies set status = 'available'
  where id = target_request.copy_id and status = 'reserved';
  perform public.offer_next_physical_waitlist(target_request.book_id, target_request.copy_id);
  insert into public.notifications(user_id, event_type, title, message, reference_id)
  values (target_request.student_id, 'physical_request_status', 'Physical book request updated',
    case when p_decision = 'rejected' then 'The library could not approve your physical book request.' else 'Your physical book request was cancelled by the library.' end,
    target_request.id);
  insert into public.audit_logs(actor_id, action, target_type, target_id, details)
  values (auth.uid(), 'physical_request_decided', 'physical_book_request', target_request.id,
    jsonb_build_object('decision', p_decision, 'book_id', target_request.book_id, 'copy_id', target_request.copy_id));
  return target_request;
end;
$$;

