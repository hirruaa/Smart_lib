create or replace function public.system_process_physical_reminders()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  target record;
  expired_offer record;
  available_copy record;
  processed_count integer := 0;
begin
  if coalesce(current_setting('request.jwt.claim.role', true), '') <> 'service_role' then
    raise exception 'Service role required';
  end if;

  for target in
    select id, student_id, book_id, copy_id
    from public.physical_book_requests
    where status = 'pending' and reservation_expires_at <= now()
    for update skip locked
  loop
    update public.physical_book_requests set status = 'expired', reservation_expires_at = null where id = target.id;
    update public.physical_book_copies set status = 'available'
    where id = target.copy_id and status = 'reserved';
    insert into public.audit_logs(actor_id, action, target_type, target_id, details)
    values (null, 'physical_request_expired', 'physical_book_request', target.id,
      jsonb_build_object('book_id', target.book_id, 'copy_id', target.copy_id));
    perform public.offer_next_physical_waitlist(target.book_id, target.copy_id);
    processed_count := processed_count + 1;
  end loop;

  for expired_offer in
    select student_id, book_id, offered_copy_id
    from public.physical_book_waitlist
    where offered_copy_id is not null and offer_expires_at <= now()
    for update skip locked
  loop
    update public.physical_book_waitlist
    set offered_copy_id = null, offer_expires_at = null
    where student_id = expired_offer.student_id and book_id = expired_offer.book_id;
    update public.physical_book_copies set status = 'available'
    where id = expired_offer.offered_copy_id and status = 'reserved';
    insert into public.audit_logs(actor_id, action, target_type, target_id, details)
    values (null, 'physical_waitlist_offer_expired', 'physical_book_copy', expired_offer.offered_copy_id,
      jsonb_build_object('book_id', expired_offer.book_id, 'student_id', expired_offer.student_id));
    perform public.offer_next_physical_waitlist(expired_offer.book_id, expired_offer.offered_copy_id);
    processed_count := processed_count + 1;
  end loop;

  for available_copy in
    select c.id, c.book_id
    from public.physical_book_copies c
    where c.status = 'available'
      and exists (select 1 from public.physical_book_waitlist w where w.book_id = c.book_id and w.offered_copy_id is null)
    order by c.book_id, c.id
    for update of c skip locked
  loop
    perform public.offer_next_physical_waitlist(available_copy.book_id, available_copy.id);
  end loop;

  for target in
    select id, student_id, book_id, due_date
    from public.physical_book_requests
    where status = 'checked_out' and due_date <= now() + interval '2 days'
    for update skip locked
  loop
    insert into public.physical_reminder_events(loan_id, reminder_type, reminder_date)
    values (target.id,
      case when target.due_date < now() then 'overdue' else 'due_soon' end,
      case when target.due_date < now() then current_date else target.due_date::date - 2 end)
    on conflict do nothing;
    if found then
      insert into public.notifications(user_id, event_type, title, message, reference_id)
      values (target.student_id,
        case when target.due_date < now() then 'physical_overdue_reminder' else 'physical_due_reminder' end,
        case when target.due_date < now() then 'Physical book overdue' else 'Physical book due soon' end,
        case when target.due_date < now() then 'Please return your overdue physical book to the library.'
          else 'Your physical book is due within two days. Please return it to the library on time.' end,
        target.id);
      insert into public.email_queue(event_type, payload)
      values ('physical_loan_reminder', jsonb_build_object(
        'student_id', target.student_id, 'book_id', target.book_id,
        'request_id', target.id, 'due_date', target.due_date,
        'reminder_type', case when target.due_date < now() then 'overdue' else 'due_soon' end));
      processed_count := processed_count + 1;
    end if;
  end loop;
  return processed_count;
end;
$$;

