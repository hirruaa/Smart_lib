create function public.request_physical_book(
  p_book_id bigint, p_copy_id bigint, p_duration_days integer, p_payment_method text,
  p_transaction_reference text default null, p_payment_proof_path text default null
)
returns public.physical_book_requests language plpgsql security definer set search_path = public as $$
declare current_user_id uuid := auth.uid(); chosen_option public.physical_loan_options; created_request public.physical_book_requests;
begin
  if current_user_id is null then raise exception 'Sign in to request a physical book'; end if;
  if p_payment_method not in ('cash', 'gcash') then raise exception 'Choose cash or GCash'; end if;
  if p_duration_days < 1 or p_duration_days > 365 then raise exception 'Choose a valid loan period'; end if;
  if not exists (select 1 from public.books where id = p_book_id and catalog_type in ('physical', 'hybrid')) then raise exception 'This title is not in the physical collection'; end if;
  if p_copy_id is not null and not exists (select 1 from public.physical_book_copies where id = p_copy_id and book_id = p_book_id) then raise exception 'The scanned copy does not belong to this book'; end if;
  if exists (select 1 from public.physical_book_requests where student_id = current_user_id and book_id = p_book_id and status in ('pending', 'checked_out')) then raise exception 'You already have an open request or loan for this book'; end if;
  select * into chosen_option from public.physical_loan_options where book_id = p_book_id and duration_days = p_duration_days and is_active;
  if chosen_option.id is null then raise exception 'That loan period is not available for this book'; end if;
  if p_payment_method = 'gcash' then
    if nullif(trim(p_transaction_reference), '') is null or nullif(trim(p_payment_proof_path), '') is null or p_payment_proof_path not like current_user_id::text || '/%' then raise exception 'Upload payment proof and enter its transaction reference'; end if;
    if not exists (select 1 from storage.objects where bucket_id = 'physical-payment-proofs' and name = p_payment_proof_path) then raise exception 'Uploaded GCash proof could not be found'; end if;
  elsif p_transaction_reference is not null or p_payment_proof_path is not null then raise exception 'Cash requests must not include online payment proof'; end if;
  insert into public.physical_book_requests(student_id, book_id, loan_option_id, copy_id, duration_days, fee_amount, payment_method, payment_status, transaction_reference, payment_proof_path, status, reservation_expires_at)
  values (current_user_id, p_book_id, chosen_option.id, null, p_duration_days, chosen_option.fee_amount, p_payment_method, case when p_payment_method = 'gcash' then 'pending_verification' else 'unpaid' end, nullif(trim(p_transaction_reference), ''), nullif(trim(p_payment_proof_path), ''), 'pending', null)
  returning * into created_request;
  return created_request;
end;
$$;

create or replace function public.admin_confirm_physical_checkout(p_request_id bigint)
returns public.physical_book_requests language plpgsql security definer set search_path = public as $$
declare target_request public.physical_book_requests; target_copy_id bigint;
begin
  if not public.is_admin() then raise exception 'Administrator access required'; end if;
  select * into target_request from public.physical_book_requests where id = p_request_id for update;
  if target_request.id is null or target_request.status <> 'pending' then raise exception 'This request is not ready for checkout'; end if;
  if target_request.payment_method = 'gcash' and target_request.payment_status <> 'pending_verification' then raise exception 'Online payment is not awaiting verification'; end if;
  select id into target_copy_id from public.physical_book_copies where book_id = target_request.book_id and status = 'available' order by id limit 1 for update skip locked;
  if target_copy_id is null then raise exception 'No physical copy is currently available'; end if;
  update public.physical_book_copies set status = 'borrowed', checked_out_at = now(), due_date = now() + make_interval(days => target_request.duration_days) where id = target_copy_id;
  update public.physical_book_requests set copy_id = target_copy_id, status = 'checked_out', payment_status = 'paid', checked_out_at = now(), due_date = now() + make_interval(days => target_request.duration_days), receipt_number = 'SL-' || to_char(now(), 'YYYYMMDD') || '-' || lpad(p_request_id::text, 6, '0') where id = p_request_id returning * into target_request;
  return target_request;
end;
$$;

