  end;
  $$;

  create or replace function public.renew_digital_loan(request_id bigint, extension_days integer default 14)
  returns public.borrow_requests language plpgsql security definer set search_path = public as $$
  declare
    updated_request public.borrow_requests;
  begin
    if auth.uid() is null then raise exception 'Authentication required'; end if;
    if extension_days < 7 or extension_days > 30 then raise exception 'Renewal must be between 7 and 30 days'; end if;
    update public.borrow_requests
    set due_date = greatest(coalesce(due_date, now()), now()) + make_interval(days => extension_days),
        renewal_count = renewal_count + 1
    where id = request_id and student_id = auth.uid() and status = 'approved'
      and returned_date is null and due_date > now() and renewal_count < 2
    returning * into updated_request;
    if updated_request.id is null then raise exception 'Loan cannot be renewed'; end if;
    return updated_request;
  end;
  $$;

