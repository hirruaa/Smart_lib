create or replace function public.cancel_physical_book_request(p_request_id bigint)
returns public.physical_book_requests
language plpgsql
security definer
set search_path = public
as $$
declare
  target_request public.physical_book_requests;
begin
  select * into target_request from public.physical_book_requests
  where id = p_request_id and student_id = auth.uid() and status = 'pending'
  for update;
  if target_request.id is null then raise exception 'Pending request not found'; end if;
  perform pg_advisory_xact_lock(hashtextextended('physical-book:' || target_request.book_id::text, 0));
  update public.physical_book_requests set status = 'cancelled', reservation_expires_at = null
  where id = p_request_id returning * into target_request;
  update public.physical_book_copies set status = 'available'
  where id = target_request.copy_id and status = 'reserved';
  perform public.offer_next_physical_waitlist(target_request.book_id, target_request.copy_id);
  insert into public.audit_logs(actor_id, action, target_type, target_id, details)
  values (auth.uid(), 'physical_request_cancelled', 'physical_book_request', target_request.id,
    jsonb_build_object('book_id', target_request.book_id, 'copy_id', target_request.copy_id));
  return target_request;
end;
$$;

create or replace function public.leave_physical_book_waitlist(p_book_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  target_offer public.physical_book_waitlist;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  perform pg_advisory_xact_lock(hashtextextended('physical-book:' || p_book_id::text, 0));
  select * into target_offer from public.physical_book_waitlist
  where student_id = auth.uid() and book_id = p_book_id
  for update;
  if target_offer.student_id is null then raise exception 'Waitlist subscription not found'; end if;
  delete from public.physical_book_waitlist where student_id = auth.uid() and book_id = p_book_id;
  if target_offer.offered_copy_id is not null then
    update public.physical_book_copies set status = 'available'
    where id = target_offer.offered_copy_id and status = 'reserved';
    perform public.offer_next_physical_waitlist(p_book_id, target_offer.offered_copy_id);
  end if;
  insert into public.audit_logs(actor_id, action, target_type, target_id, details)
  values (auth.uid(), 'physical_waitlist_left', 'book', p_book_id,
    jsonb_build_object('released_copy_id', target_offer.offered_copy_id));
end;
$$;

