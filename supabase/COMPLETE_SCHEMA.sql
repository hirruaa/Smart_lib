  create or replace function public.search_books(p_query text, p_limit integer default 10)
  returns table(
    id bigint,
    title text,
    author text,
    category text,
    description text,
    pdf_url text,
    available_copies integer,
    rank double precision
  )
  language sql
  stable
  security invoker
  as $$
    select b.id, b.title, b.author, b.category, b.description, b.pdf_url,
          b.available_copies,
          ts_rank(b.search_vector, plainto_tsquery('english', p_query)) as rank
    from public.books b
    where b.search_vector @@ plainto_tsquery('english', p_query)
    order by rank desc
    limit least(greatest(coalesce(p_limit, 10), 1), 50);
  $$;

