create or replace function public.admin_confirm_physical_checkout(p_request_id bigint)
returns public.physical_book_requests
language plpgsql security definer set search_path = public
as $$
declare
  target_request public.physical_book_requests;
begin
  if not public.is_admin() then raise exception 'Administrator access required'; end if;
  select * into target_request from public.physical_book_requests
  where id = p_request_id for update;
  if target_request.id is null or target_request.status <> 'pending'
    or target_request.reservation_expires_at <= now() then
    raise exception 'This request has expired or is not ready for checkout';
  end if;
  if target_request.payment_method = 'gcash' and target_request.payment_status <> 'pending_verification' then
    raise exception 'Online payment is not awaiting verification';
  end if;
  perform 1 from public.physical_book_copies
  where id = target_request.copy_id and book_id = target_request.book_id and status = 'reserved'
  for update;
  if not found then raise exception 'The reserved physical copy is no longer available'; end if;

  update public.physical_book_copies set status = 'borrowed', checked_out_at = now(),
    due_date = now() + make_interval(days => target_request.duration_days)
  where id = target_request.copy_id;
  update public.physical_book_requests
  set status = 'checked_out', payment_status = 'paid', checked_out_at = now(),
      reservation_expires_at = null,
      due_date = now() + make_interval(days => target_request.duration_days),
      receipt_number = 'SL-' || to_char(now(), 'YYYYMMDD') || '-' || lpad(p_request_id::text, 6, '0')
  where id = p_request_id returning * into target_request;
  insert into public.notifications(user_id, event_type, title, message, reference_id)
  values (target_request.student_id, 'physical_checkout', 'Physical book checked out',
    'Your payment and checkout were confirmed. Your digital receipt is ready in your physical library account.',
    target_request.id);
