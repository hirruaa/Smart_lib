create or replace function public.offer_next_physical_waitlist(
  p_book_id bigint,
  p_copy_id bigint default null
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  available_copy_id bigint;
  next_member record;
begin
  perform pg_advisory_xact_lock(hashtextextended('physical-book:' || p_book_id::text, 0));
  if not exists (
    select 1 from public.physical_loan_options
    where book_id = p_book_id and is_active
  ) then return null; end if;

  if p_copy_id is null then
    select id into available_copy_id
    from public.physical_book_copies
    where book_id = p_book_id and status = 'available'
    order by id
    limit 1
    for update skip locked;
  else
    select id into available_copy_id
    from public.physical_book_copies
    where id = p_copy_id and book_id = p_book_id and status = 'available'
    for update skip locked;
  end if;

  if available_copy_id is null then return null; end if;

  for next_member in
    select student_id, book_id
    from public.physical_book_waitlist
    where book_id = p_book_id and offered_copy_id is null
    order by created_at, student_id
    for update skip locked
  loop
    if exists (
      select 1 from public.physical_book_requests
      where student_id = next_member.student_id and status in ('pending', 'checked_out', 'lost')
        and (book_id = p_book_id or status = 'lost' or (status = 'checked_out' and due_date < now()))
    ) then
      delete from public.physical_book_waitlist
      where student_id = next_member.student_id and book_id = p_book_id;
      continue;
    end if;

    update public.physical_book_copies
    set status = 'reserved'
    where id = available_copy_id and status = 'available';
    if not found then return null; end if;

    update public.physical_book_waitlist
    set offered_copy_id = available_copy_id,
        offer_expires_at = now() + interval '24 hours'
    where student_id = next_member.student_id and book_id = p_book_id;

    insert into public.notifications(user_id, event_type, title, message, reference_id)
    values (
      next_member.student_id,
      'physical_book_available',
      'A physical book is reserved for you',
      'A copy is being held for you for 24 hours. Open your physical library page to choose a loan period and submit your request.',
      p_book_id
    );
    insert into public.audit_logs(actor_id, action, target_type, target_id, details)
    values (auth.uid(), 'physical_waitlist_offer_created', 'physical_book_copy', available_copy_id,
      jsonb_build_object('book_id', p_book_id, 'student_id', next_member.student_id, 'expires_at', now() + interval '24 hours'));
    return available_copy_id;
  end loop;

  return null;
end;
$$;

revoke all on function public.offer_next_physical_waitlist(bigint, bigint) from public, anon, authenticated;

create or replace function public.admin_add_physical_copies(
  p_book_id bigint,
  p_quantity integer,
  p_code_prefix text,
  p_location text default null
)
returns setof public.physical_book_copies
language plpgsql
security definer
set search_path = public
as $$
declare
  next_code integer;
  created_copy public.physical_book_copies;
begin
  if not public.is_admin() then raise exception 'Administrator access required'; end if;
  if p_quantity < 1 or p_quantity > 100 then raise exception 'Add between 1 and 100 copies at a time'; end if;
  if nullif(trim(p_code_prefix), '') is null or char_length(trim(p_code_prefix)) > 32
    or trim(p_code_prefix) !~ '^[A-Za-z0-9_-]+$' then
    raise exception 'Enter a valid copy-code prefix';
  end if;
  if not exists (select 1 from public.books where id = p_book_id) then raise exception 'Book not found'; end if;

  perform pg_advisory_xact_lock(hashtext(trim(p_code_prefix)));
  perform pg_advisory_xact_lock(hashtextextended('physical-book:' || p_book_id::text, 0));
  update public.books set catalog_type = 'hybrid' where id = p_book_id and catalog_type = 'digital';

  select coalesce(max(substring(copy_code from length(trim(p_code_prefix)) + 2)::integer), 0) + 1
  into next_code
  from public.physical_book_copies
  where copy_code like trim(p_code_prefix) || '-%'
    and substring(copy_code from length(trim(p_code_prefix)) + 2) ~ '^[0-9]+$';

  for created_copy in
    insert into public.physical_book_copies(book_id, copy_code, location)
    select p_book_id, trim(p_code_prefix) || '-' || lpad((next_code + series.idx)::text, 3, '0'), nullif(trim(p_location), '')
    from generate_series(0, p_quantity - 1) as series(idx)
    returning *
  loop
    perform public.offer_next_physical_waitlist(p_book_id, created_copy.id);
    insert into public.audit_logs(actor_id, action, target_type, target_id, details)
    values (auth.uid(), 'physical_copy_created', 'physical_book_copy', created_copy.id,
      jsonb_build_object('book_id', p_book_id, 'copy_code', created_copy.copy_code));
    return next created_copy;
  end loop;
end;
$$;

drop function if exists public.request_physical_book(bigint, bigint, integer, text, text, text);
create function public.request_physical_book(
  p_book_id bigint,
  p_copy_id bigint,
  p_duration_days integer,
  p_payment_method text,
  p_transaction_reference text default null,
  p_payment_proof_path text default null
)
returns public.physical_book_requests
language plpgsql
security definer
set search_path = public
as $$
declare
  current_user_id uuid := auth.uid();
  book_catalog_type text;
  chosen_option public.physical_loan_options;
  selected_copy_id bigint;
  created_request public.physical_book_requests;
begin
  if current_user_id is null then raise exception 'Sign in to request a physical book'; end if;
  if p_payment_method not in ('cash', 'gcash') then raise exception 'Choose cash or GCash'; end if;
  if p_duration_days < 1 or p_duration_days > 365 then raise exception 'Choose a valid loan period'; end if;

  perform pg_advisory_xact_lock(hashtextextended('physical-member:' || current_user_id::text, 0));
  perform pg_advisory_xact_lock(hashtextextended('physical-book:' || p_book_id::text, 0));
  select catalog_type into book_catalog_type from public.books where id = p_book_id;
  if book_catalog_type not in ('physical', 'hybrid') then raise exception 'This title is not in the physical collection'; end if;

  if exists (
    select 1 from public.physical_book_requests
    where student_id = current_user_id and book_id = p_book_id and status in ('pending', 'checked_out')
  ) then raise exception 'You already have an open request or loan for this book'; end if;
  if exists (
    select 1 from public.physical_book_requests
    where student_id = current_user_id and status in ('checked_out', 'lost')
      and (status = 'lost' or due_date < now())
  ) then raise exception 'Resolve your overdue or lost library book before requesting another'; end if;

  select * into chosen_option from public.physical_loan_options
  where book_id = p_book_id and duration_days = p_duration_days and is_active;
  if chosen_option.id is null then raise exception 'That loan period is not available for this book'; end if;

  if p_payment_method = 'gcash' then
    if nullif(trim(p_transaction_reference), '') is null
      or char_length(trim(p_transaction_reference)) > 100
      or nullif(trim(p_payment_proof_path), '') is null
      or p_payment_proof_path not like current_user_id::text || '/%' then
      raise exception 'Upload payment proof and enter its transaction reference';
    end if;
    if not exists (
      select 1 from storage.objects where bucket_id = 'physical-payment-proofs' and name = p_payment_proof_path
    ) then raise exception 'Uploaded GCash proof could not be found'; end if;
  elsif p_transaction_reference is not null or p_payment_proof_path is not null then
    raise exception 'Cash requests must not include online payment proof';
  end if;

  if p_copy_id is null then
    select id into selected_copy_id from public.physical_book_copies
    where book_id = p_book_id and status = 'available'
    order by id limit 1 for update skip locked;
  else
    select id into selected_copy_id from public.physical_book_copies
    where id = p_copy_id and book_id = p_book_id and status = 'available'
    for update skip locked;
  end if;
  if selected_copy_id is null then raise exception 'That physical copy is not available; join the waitlist instead'; end if;

  insert into public.physical_book_requests (
    student_id, book_id, loan_option_id, copy_id, duration_days, fee_amount, payment_method,
    payment_status, transaction_reference, payment_proof_path, status, reservation_expires_at
  ) values (
    current_user_id, p_book_id, chosen_option.id, selected_copy_id, p_duration_days, chosen_option.fee_amount,
    p_payment_method,
    case when p_payment_method = 'gcash' then 'pending_verification' else 'unpaid' end,
    nullif(trim(p_transaction_reference), ''), nullif(trim(p_payment_proof_path), ''),
    'pending', now() + interval '24 hours'
  ) returning * into created_request;

  update public.physical_book_copies set status = 'reserved' where id = selected_copy_id;
  delete from public.physical_book_waitlist
  where student_id = current_user_id and book_id = p_book_id;
  insert into public.audit_logs(actor_id, action, target_type, target_id, details)
  values (current_user_id, 'physical_request_created', 'physical_book_request', created_request.id,
    jsonb_build_object('book_id', p_book_id, 'copy_id', selected_copy_id, 'payment_method', p_payment_method));
  return created_request;
end;
$$;

