  current_user_id uuid := auth.uid();
begin
  if current_user_id is null then raise exception 'Sign in to turn on availability alerts'; end if;
  if exists (
    select 1 from public.physical_book_copies
    where book_id = p_book_id and status = 'available'
  ) then raise exception 'A copy is available now; submit a physical loan request instead'; end if;
  if exists (
    select 1 from public.physical_book_requests
    where student_id = current_user_id and book_id = p_book_id
      and status in ('pending', 'checked_out')
  ) then raise exception 'You already have an open request or loan for this book'; end if;
