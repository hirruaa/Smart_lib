CREATE OR REPLACE FUNCTION public.enqueue_borrow_request_notifications()
RETURNS trigger AS $$
BEGIN
  IF TG_OP = 'UPDATE' THEN
    IF (OLD.status IS DISTINCT FROM NEW.status) THEN
      IF NEW.status IN ('approved', 'rejected') THEN
        INSERT INTO public.email_queue(event_type, payload)
        VALUES (
          'borrow_request_status',
          jsonb_build_object(
            'student_id', NEW.student_id,
            'book_id', NEW.book_id,
            'status', NEW.status,
            'request_id', NEW.id
          )
        );
      END IF;
    END IF;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

