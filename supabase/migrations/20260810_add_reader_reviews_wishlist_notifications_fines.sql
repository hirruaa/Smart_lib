-- 8) Helper function to calculate fines (call from a scheduled job)
CREATE OR REPLACE FUNCTION public.calculate_overdue_fines(daily_rate numeric DEFAULT 0.5)
RETURNS void AS $$
DECLARE
  br RECORD;
  days_overdue integer;
  fine_amount numeric;
BEGIN
  FOR br IN
    SELECT id, student_id, due_date
    FROM public.borrow_requests
    WHERE status = 'approved' AND due_date IS NOT NULL AND (returned_date IS NULL OR returned_date > due_date)
  LOOP
    days_overdue := GREATEST(0, DATE_PART('day', now()::date - br.due_date::date));
    IF days_overdue > 0 THEN
      fine_amount := days_overdue * daily_rate;
      -- upsert a fine linked to this borrow_request
      INSERT INTO public.fines(borrow_request_id, student_id, amount)
      VALUES (br.id, br.student_id, fine_amount)
      ON CONFLICT (borrow_request_id) DO UPDATE SET amount = EXCLUDED.amount, status = 'unpaid', created_at = timezone('utc'::text, now());
    END IF;
  END LOOP;
END;
$$ LANGUAGE plpgsql;

